function makeLocale(code, tag, messages = {}) {
    const text = (message, variables = {}) => {
        if (typeof message !== "string") return message;
        const translated = Object.hasOwn(messages, message) ? messages[message] : message;
        return translated.replace(/\{(\w+)\}/g, (placeholder, key) => variables[key] ?? placeholder);
    };
    return {
        code, tag, text,
        shortTime: new Intl.DateTimeFormat(tag, {month: "short", day: "numeric", hour: "numeric", minute: "2-digit"}),
        cutoffTime: new Intl.DateTimeFormat(tag, {
            year: "numeric", month: "short", day: "numeric", hour: "numeric", minute: "2-digit", timeZoneName: "short",
        }),
        planDate: new Intl.DateTimeFormat(tag, {year: "numeric", month: "short", day: "numeric", timeZone: "UTC"}),
        planList: new Intl.ListFormat(tag, {style: "long", type: "conjunction"}),
    };
}

const interfaceLocales = {en: makeLocale("en", "en-US"), zh: makeLocale("zh", "zh-CN", chinese)};

function savedInterfaceLocale() {
    try {
        return localStorage.getItem(interfaceLanguageKey) === "zh" ? interfaceLocales.zh : interfaceLocales.en;
    } catch {
        return interfaceLocales.en;
    }
}

function saveInterfaceLocale(locale) {
    try {
        localStorage.setItem(interfaceLanguageKey, locale.code);
    } catch {
        // The selector still works for the current page when browser storage is unavailable.
    }
}

function localizeDiagnostic(message, t) {
    const replay = " You can also choose Fixture replay.";
    if (message.endsWith(replay)) return localizeDiagnostic(message.slice(0, -replay.length), t) + t(replay);
    const invalid = /^(?<provider>.*?) configuration is invalid\. Check \[(?<section>.*?)\] in config\.local\.toml and (?<variable>.*?)\.$/.exec(message);
    if (invalid) return t("{provider} configuration is invalid. Check [{section}] in config.local.toml and {variable}.",
        invalid.groups);
    const unavailable = /^(?<provider>.*?) is unavailable\. Set (?<variable>.*?) or update (?<setting>.*?) in config\.local\.toml\.$/.exec(message);
    if (unavailable) return t("{provider} is unavailable. Set {variable} or update {setting} in config.local.toml.",
        unavailable.groups);
    for (const prefix of ["Enter a value for ", "Choose a listed value for "]) {
        if (message.startsWith(prefix)) return t(prefix + "{label}", {label: message.slice(prefix.length)});
    }
    return t(message);
}
